// FSO.LotView.Model.WallTile / WallSegments (from XmlHouse.cs)
#pragma once
#include <cstdint>
namespace FSO { namespace LotView { namespace Model {

enum class WallSegments : int {
    TopLeft = 1,
    TopRight = 2,
    BottomRight = 4,
    BottomLeft = 8,
    HorizontalDiag = 16,
    VerticalDiag = 32,
    AnyDiag = 0x30,
    AnyAdj = 0xF
};
inline WallSegments operator|(WallSegments a, WallSegments b) { return (WallSegments)((int)a | (int)b); }
inline WallSegments operator&(WallSegments a, WallSegments b) { return (WallSegments)((int)a & (int)b); }
inline WallSegments operator~(WallSegments a) { return (WallSegments)(~(int)a); }
inline WallSegments& operator|=(WallSegments& a, WallSegments b) { a = a | b; return a; }
inline WallSegments& operator&=(WallSegments& a, WallSegments b) { a = a & b; return a; }
inline bool operator>(WallSegments a, int b) { return (int)a > b; }
inline bool operator==(WallSegments a, int b) { return (int)a == b; }
inline bool operator!=(WallSegments a, int b) { return (int)a != b; }

struct WallTile {
    WallSegments Segments = (WallSegments)0;
    //the patterns of each side of the tile's wall.
    uint16_t TopLeftPattern = 0;
    uint16_t TopRightPattern = 0;
    uint16_t BottomLeftPattern = 0;
    uint16_t BottomRightPattern = 0;
    //the style of the wall at the top left and top right. bottom left and bottom right are to be obtained from the tiles in those directions.
    //1 generally means "normal wall". Not sure how to deal with cutouts while keeping these as "normal wall".
    uint16_t TopLeftStyle = 0;
    uint16_t TopRightStyle = 0;

    bool TopLeftSolid() const { return (Segments & WallSegments::TopLeft) > 0 && !TopLeftDoor; }
    bool TopRightSolid() const { return (Segments & WallSegments::TopRight) > 0 && !TopRightDoor; }
    bool TopLeftThick() const { return (Segments & WallSegments::TopLeft) > 0 && (TopLeftStyle == 1 || TopLeftStyle == 255); }
    bool TopRightThick() const { return (Segments & WallSegments::TopRight) > 0 && (TopRightStyle == 1 || TopRightStyle == 255); }

    //Placement never seems to be not zero, so it's not included for now.
    //don't include below information when serializing as it will be generated by the client upon load
    uint16_t ObjSetTLStyle = 0; //custom styles set by objects (windows and doors)
    uint16_t ObjSetTRStyle = 0;
    bool TopLeftDoor = false;
    bool TopRightDoor = false;
    WallSegments OccupiedWalls = (WallSegments)0;
};

}}}
