# Generates src/app/FontData.h: anti-aliased proportional bitmap fonts rasterized from Inter
# (SIL Open Font License 1.1, https://github.com/rsms/inter). 4-bit alpha, Latin-1 (32..255).
# usage: python3 genfont.py /usr/share/fonts/opentype/inter > ../FontData.h
import sys
from PIL import Image, ImageDraw, ImageFont
d = sys.argv[1]
fonts = [("Small", d + "/Inter-Medium.otf", 10), ("Bold", d + "/Inter-Bold.otf", 12), ("Title", d + "/Inter-Bold.otf", 17)]
out = []
out.append("// GENERATED by src/app/tools/genfont.py - do not edit.")
out.append("// Glyphs rasterized from the Inter typeface (c) The Inter Project Authors, SIL Open Font License 1.1.")
out.append("// This generated glyph data is a derivative of Inter and is licensed under the SIL OFL 1.1 (LICENSES/OFL-1.1-Inter.txt).")
out.append("#pragma once\n#include <cstdint>\nnamespace simapp { namespace fontdata {")
out.append("struct Glyph { uint16_t offset; int8_t xoff, yoff; uint8_t w, h, advance; };")
for name, path, size in fonts:
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    data = bytearray(); glyphs = []
    for cp in range(32, 256):
        ch = chr(cp)
        if 127 <= cp < 160: ch = '?'
        adv = int(round(f.getlength(ch)))
        bbox = f.getbbox(ch)
        if bbox is None or bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
            glyphs.append((len(data)//1, 0, 0, 0, 0, adv)); continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255)
        px = list(im.getdata())
        off = len(data)
        nib = [min(15, (p + 8) // 17) for p in px]
        if len(nib) % 2: nib.append(0)
        for i in range(0, len(nib), 2): data.append(nib[i] | (nib[i+1] << 4))
        glyphs.append((off, x0, y0, w, h, adv))
    out.append("static const uint8_t %sBits[%d] = {" % (name, max(1, len(data))))
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(b) for b in data[i:i+24]) + ",")
    out.append("};")
    out.append("static const Glyph %sGlyphs[224] = {" % name)
    for g in glyphs: out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append("static const int %sAscent = %d, %sLineHeight = %d;" % (name, asc, name, asc + desc))
out.append("}}")
print("\n".join(out))
